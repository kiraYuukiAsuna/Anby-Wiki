import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(readFileSync(new URL('../lib/history/visual-diff.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {indexDocument,buildVisualChanges,changedTextRanges}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const p=(id,text=id)=>({id,type:'paragraph',content:[{type:'text',text}]});
const container=(id,children)=>({id,type:'quote',children});
const index=children=>indexDocument({type:'document',schema_version:1,children});
const compare=(a,b,changes)=>buildVisualChanges(index(a),index(b),{changes});
const c=(id,type,extra={})=>({blockId:id,type,parentId:'',...extra});
assert.deepEqual(compare([p('a'),p('b')],[p('n'),p('a'),p('b')],[c('n','added'),c('a','moved'),c('b','moved')]).map(c=>[c.id,c.types]),[['n',['added']]]);
assert.deepEqual(compare([p('a'),p('b'),p('c')],[p('c'),p('a'),p('b')],[c('a','moved'),c('b','moved'),c('c','moved')]).map(c=>c.id),['c']);
assert.deepEqual(compare([p('a'),p('b')],[p('b')],[c('a','removed'),c('b','moved')]).map(c=>c.id),['a']);
assert.deepEqual(compare([], [container('q',[p('p')])],[c('q','added'),c('p','added')]).map(c=>c.id),['q']);
assert.deepEqual(compare([container('q',[p('p')])],[],[c('q','removed'),c('p','removed')]).map(c=>c.id),['q']);
assert.deepEqual(compare([container('q',[p('p')]),p('a'),p('b')],[p('a'),p('b'),container('q',[p('p')])],[c('q','moved'),c('p','moved')]).map(c=>c.id),['q']);
assert.deepEqual(compare([container('q',[p('p')]),container('r',[])],[container('q',[]),container('r',[p('p')])],[c('p','moved')]).map(c=>[c.id,c.types]),[['p',['moved']]]);
assert.deepEqual(compare([p('a'),p('b'),p('c')],[p('c','new'),p('a'),p('b')],[c('c','changed',{fields:[{field:'content'}]}),c('c','moved')]).map(c=>c.types),[['changed','moved']]);
assert.deepEqual(compare([p('a','same')],[p('b','same')],[c('a','removed'),c('b','added')]).map(c=>c.types),[['added'],['removed']]);
assert.deepEqual(changedTextRanges('负责记录作战资料','负责整理与校对作战资料'),{before:[[2,4]],after:[[2,7]]});
assert.deepEqual(changedTextRanges('👩🏽‍💻很好','👩🏽‍💻真好'),{before:[[7,8]],after:[[7,8]]});
assert.deepEqual(changedTextRanges('甲一乙二丙','甲三乙四丙'),{before:[[1,2],[3,4]],after:[[1,2],[3,4]]});
assert.deepEqual(changedTextRanges('same','same'),{before:[],after:[]});
assert.deepEqual(changedTextRanges('x'.repeat(2000),'y'.repeat(2000)),{before:[[0,2000]],after:[[0,2000]]});
assert.deepEqual(compare([p('a')],[p('a')],[]),[]);
console.log('PASS 15 visual normalization and Unicode text-diff checks');
